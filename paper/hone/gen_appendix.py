#!/usr/bin/env python
"""Appendix tables of the HoNE paper, generated from results/final_v2/summary.json only (no hand-typed numbers).

  python paper/hone/gen_appendix.py   ->  paper/hone/appendix_tables.tex
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
S = json.loads((ROOT / "results/final_v2/summary.json").read_text())
CS, T = S["class_evals"], S["transfer"]
DETS = [("MSP", "MSP"), ("Energy", "Energy"), ("P_attack", "P(att.)$^\\dagger$"), None,
        ("AHSD_stress", "Stress"), ("Mahalanobis", "Mahal."), ("kNN", "kNN"), None,
        ("IF", "IF"), ("OCSVM", "OCSVM"), ("PCA", "PCA"), ("AE", "AE"), None, ("Wilkie_CLAD", "CLAD"), None,
        ("XGBoost", "XGBoost")]
ABBR = {"Bot": "Bot", "BruteForce": "Brute F.", "DDoS": "DDoS", "DoS": "DoS", "Infiltration": "Infil.", "Web Attacks": "Web",
        "Analysis": "Anal.", "Backdoor": "Backd.", "Exploits": "Expl.", "Fuzzers": "Fuzz.", "Generic": "Gen.",
        "Reconnaissance": "Recon.", "Shellcode": "Shellc.", "ddos": "ddos", "injection": "inject.", "password": "passw.",
        "scanning": "scan.", "xss": "xss", "Infilteration": "Infil.", "mitm": "mitm", "ransomware": "ransom.",
        "portscan": "portscan", "dos_hulk": "DoS Hulk"}
TABLES = [("loaco_D1fam", "Per-class AUC, LOACO D1 (CIC-IDS2018 families). Mean of five seeds; s.d.\\ = mean seed standard deviation over classes.", "a_l1"),
          ("loaco_D2", "Per-class AUC, LOACO D2 (UNSW-NB15).", "a_l2"),
          ("loaco_D3", "Per-class AUC, LOACO D3 (ToN-IoT).", "a_l3"),
          ("nn_D1", "Per-class AUC, natural novelty D1.", "a_n1"),
          ("nn_D3", "Per-class AUC, natural novelty D3.", "a_n3"),
          ("nn_D5", "Per-class AUC, natural novelty D5 (Lycos2017).", "a_n5"),
          ("loaco_D5pb", "AUC, purged-block LOACO D5 (single fold).", "a_p5")]


def class_table(e, cap, lab):
    cls = CS[e]["classes"]
    rows = []
    for d in DETS:
        if d is None:
            rows.append("\\midrule")
            continue
        key, name = d
        c = CS[e]["cells"][key]
        sd = sum(c[k]["std"] for k in cls) / len(cls)
        rows.append(f"{name} & " + " & ".join(f"{c[k]['mean']:.2f}" for k in cls) + f" & {sd:.3f}\\\\")
    return ("\\begin{table}[!t]\n\\centering\n\\scriptsize\n\\setlength{\\tabcolsep}{2.6pt}\n"
            f"\\caption{{{cap}}}\n\\label{{tab:{lab}}}\n\\begin{{tabular}}{{l{'c' * (len(cls) + 1)}}}\n\\toprule\n"
            "Detector & " + " & ".join(ABBR[k] for k in cls) + " & s.d.\\\\\n\\midrule\n" + "\n".join(rows)
            + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")


def transfer_table():
    rows = []
    for d in DETS:
        if d is None:
            continue
        key, name = d
        cells = []
        for src in ("D1", "D2", "D3"):
            for tgt in ("D1", "D2", "D3", "D4"):
                v = f"{T[key][src][tgt]['mean']:.2f}"
                cells.append(f"\\cellcolor{{black!10}}{v}" if src == tgt else v)
        rows.append(f"{name} & " + " & ".join(cells) + "\\\\")
    return ("\\begin{table*}[!t]\n\\centering\n\\scriptsize\n\\setlength{\\tabcolsep}{3pt}\n"
            "\\caption{Zero-shot transfer AUC (mean of five seeds). Rows: detector; column groups: source dataset; columns: "
            "target. Diagonal cells (in-domain) in grey.}\n\\label{tab:a_transfer}\n\\begin{tabular}{lcccccccccccc}\n\\toprule\n"
            " & \\multicolumn{4}{c}{Source D1} & \\multicolumn{4}{c}{Source D2} & \\multicolumn{4}{c}{Source D3}\\\\\n"
            "\\cmidrule(lr){2-5}\\cmidrule(lr){6-9}\\cmidrule(lr){10-13}\n"
            "Detector & D1 & D2 & D3 & D4 & D1 & D2 & D3 & D4 & D1 & D2 & D3 & D4\\\\\n\\midrule\n" + "\n".join(rows)
            + "\n\\bottomrule\n\\end{tabular}\n\\end{table*}\n")


out = "% generated by paper/hone/gen_appendix.py from results/final_v2/summary.json; do not edit\n"
out += "\n".join(class_table(*t) for t in TABLES) + "\n" + transfer_table()
(Path(__file__).parent / "appendix_tables.tex").write_text(out)
print("appendix_tables.tex written")
